    <h1>Politique de confidentialité</h1>
    <p class="muted">Dernière mise à jour : 5 février 2026</p>

    <p>
        La présente politique de confidentialité explique comment <strong>conttron</strong> traite
        les données des utilisateurs lorsqu’ils utilisent notre application et notre site.
        En utilisant nos services, vous acceptez les pratiques décrites ci-dessous.
    </p>

    <h2>1. Données collectées</h2>
    <p>Selon les fonctionnalités utilisées, nous pouvons collecter :</p>
    <ul>
        <li>Informations d’identification fournies par l’utilisateur (ex. nom, téléphone, e‑mail).</li>
        <li>Données d’usage (ex. interactions, pages consultées, journaux techniques).</li>
        <li>Données de l’appareil (ex. modèle, version du système, identifiants techniques).</li>
    </ul>

    <h2>2. Données sensibles et permissions</h2>
    <p>
        Si certaines fonctionnalités nécessitent l’accès à des données sensibles (ex. contacts,
        téléphone, localisation), nous demandons votre autorisation préalable. Vous pouvez refuser
        ou retirer ces autorisations à tout moment depuis les paramètres de votre appareil.
    </p>

    <h2>3. Finalités du traitement</h2>
    <ul>
        <li>Fournir et améliorer le service.</li>
        <li>Assurer la sécurité, la prévention de la fraude et la conformité.</li>
        <li>Support et communication avec les utilisateurs.</li>
    </ul>

    <h2>4. Partage des données</h2>
    <p>
        Nous ne vendons pas vos données. Nous pouvons partager certaines données avec des
        prestataires de service strictement nécessaires (hébergement, messagerie, analytics),
        uniquement pour fournir le service et dans le respect de la confidentialité.
    </p>

    <h2>5. Conservation</h2>
    <p>
        Les données sont conservées uniquement le temps nécessaire aux finalités décrites,
        puis supprimées ou anonymisées conformément aux obligations légales.
    </p>

    <h2>6. Sécurité</h2>
    <p>
        Nous mettons en œuvre des mesures techniques et organisationnelles pour protéger vos
        données contre l’accès non autorisé, la perte ou l’altération.
    </p>

    <h2>7. Droits des utilisateurs</h2>
    <p>
        Vous pouvez demander l’accès, la rectification, la suppression ou la limitation de
        vos données personnelles. Pour exercer ces droits, contactez-nous via les coordonnées
        ci‑dessous.
    </p>

    <h2>8. Enfants</h2>
    <p>
        Si notre application s’adresse à des enfants de moins de 13 ans, nous appliquons des règles
        spécifiques de protection et ne collectons pas de données personnelles sans le consentement
        d’un parent ou tuteur légal.
    </p>

    <h2>9. Contact</h2>
    <p>
        Pour toute question liée à la confidentialité, vous pouvez nous contacter à l’adresse suivante :
